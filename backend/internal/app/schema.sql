CREATE TABLE IF NOT EXISTS metadata (key TEXT PRIMARY KEY, value TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS books (
 id INTEGER PRIMARY KEY AUTOINCREMENT, title TEXT NOT NULL, subtitle TEXT NOT NULL DEFAULT '', description TEXT NOT NULL DEFAULT '',
 category TEXT NOT NULL DEFAULT '', color TEXT NOT NULL DEFAULT '#397d67', created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS users (
 id INTEGER PRIMARY KEY AUTOINCREMENT, name TEXT NOT NULL, email TEXT UNIQUE, password_hash TEXT,
 role TEXT NOT NULL DEFAULT 'user' CHECK(role IN ('user','admin')), guest INTEGER NOT NULL DEFAULT 1,
 daily_goal INTEGER NOT NULL DEFAULT 20 CHECK(daily_goal BETWEEN 1 AND 500), exam_date TEXT NOT NULL DEFAULT '',
 active_book_id INTEGER REFERENCES books(id) ON DELETE SET NULL, created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS sessions (
 token_hash TEXT PRIMARY KEY, user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE, expires_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS sessions_user ON sessions(user_id);
CREATE TABLE IF NOT EXISTS words (
 id INTEGER PRIMARY KEY AUTOINCREMENT, book_id INTEGER NOT NULL REFERENCES books(id) ON DELETE CASCADE,
 text TEXT NOT NULL COLLATE NOCASE, phonetic TEXT NOT NULL DEFAULT '', meaning TEXT NOT NULL,
 example TEXT NOT NULL DEFAULT '', example_meaning TEXT NOT NULL DEFAULT '', UNIQUE(book_id,text)
);
CREATE TABLE IF NOT EXISTS progress (
 user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE, word_id INTEGER NOT NULL REFERENCES words(id) ON DELETE CASCADE,
 status TEXT NOT NULL DEFAULT 'new' CHECK(status IN ('new','learning','mastered')),
 reinforce INTEGER NOT NULL DEFAULT 0, due_at TEXT NOT NULL DEFAULT '', repetitions INTEGER NOT NULL DEFAULT 0,
 interval_days REAL NOT NULL DEFAULT 0, ease REAL NOT NULL DEFAULT 2.5, updated_at TEXT NOT NULL,
 PRIMARY KEY(user_id,word_id)
);
CREATE INDEX IF NOT EXISTS progress_due ON progress(user_id,due_at);
CREATE TABLE IF NOT EXISTS learn_progress (
 user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE, word_id INTEGER NOT NULL REFERENCES words(id) ON DELETE CASCADE,
 stage INTEGER NOT NULL DEFAULT 0 CHECK(stage BETWEEN 0 AND 2), revision INTEGER NOT NULL DEFAULT 0 CHECK(revision>=0),
 updated_at TEXT NOT NULL, PRIMARY KEY(user_id,word_id)
);
CREATE TABLE IF NOT EXISTS favorites (
 user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE, word_id INTEGER NOT NULL REFERENCES words(id) ON DELETE CASCADE,
 PRIMARY KEY(user_id,word_id)
);
CREATE TABLE IF NOT EXISTS answers (
 id INTEGER PRIMARY KEY AUTOINCREMENT, user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 word_id INTEGER REFERENCES words(id) ON DELETE SET NULL, submitted_word_id INTEGER NOT NULL, word_text TEXT NOT NULL, word_meaning TEXT NOT NULL,
 mode TEXT NOT NULL, answer TEXT NOT NULL, event_id TEXT NOT NULL, created_at TEXT NOT NULL, UNIQUE(user_id,event_id)
);
CREATE INDEX IF NOT EXISTS answers_user_time ON answers(user_id,created_at);
CREATE INDEX IF NOT EXISTS answers_time ON answers(created_at);
CREATE TABLE IF NOT EXISTS learn_answer_steps (
 answer_id INTEGER PRIMARY KEY REFERENCES answers(id) ON DELETE CASCADE,
 request_stage INTEGER NOT NULL CHECK(request_stage IN (0,1)), request_revision INTEGER NOT NULL CHECK(request_revision>=0),
 result_stage INTEGER NOT NULL CHECK(result_stage BETWEEN 0 AND 2), result_revision INTEGER NOT NULL CHECK(result_revision>0)
);
CREATE TABLE IF NOT EXISTS navigation (
 id TEXT PRIMARY KEY, label TEXT NOT NULL, path TEXT NOT NULL UNIQUE, icon TEXT NOT NULL, enabled INTEGER NOT NULL, sort_order INTEGER NOT NULL
);
